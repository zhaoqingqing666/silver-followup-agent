package com.team.silveragent.agent;

import java.util.List;

/**
 * 「这句话在宣称一件写操作已经办好了」的判定。
 *
 * <p>只回答这一件事，不回答「该不该办」「办得对不对」——那些分别由
 * {@link com.team.silveragent.application.ActionValidator}（这条路能不能直接说）
 * 和各自的确认流程负责。
 *
 * <p>存在的理由是一个实测过的失败模式：模型改写的回复里会自行宣布「已经记下了」，
 * 而这一轮其实一条都没写。回复是老人唯一能看到的东西，说了没做，比明确说「我还没记」
 * 严重得多——他不会再问第二次。所以「说到」必须由「做到」来授权：权威草稿里没有的
 * 完成说法，回复里也不许有。
 *
 * <p>词表刻意只收<b>完成态</b>的说法（「已记下」「记好了」），不收动作本身
 * （「记下」「帮您记」）。「您说的血压 130，需要我记下吗？」是在问，不是在声称，
 * 按完成态取词就不会误伤。
 *
 * <p>{@code LlmAnswerGenerator}（回答阶段）与 {@code ActionValidator}（模型直接作答那条路）
 * 共用这一份：两处各写一张表，迟早一处加了一处没加，而漏掉的那处正是谎报的出口。
 */
public final class WriteClaims {

    /**
     * 完成态的说法。分四类只为读起来清楚，判定时一视同仁：
     * 预约/改期、取消、通知、备忘与健康数值（后两类是「记一下……」被改写成「已经记下了」的重灾区）。
     */
    private static final List<String> CLAIMS = List.of(
            // 预约 / 改期
            "预约成功", "已预约", "已经预约", "已为您预约", "预约好了", "已改期", "改期成功",
            // 取消
            "取消成功", "已取消", "已经取消", "已为您取消",
            // 通知家属
            "已通知", "已经通知", "已发给", "已经发给", "已发送", "已经发送",
            // 备忘 / 健康数值 / 提醒
            "已记下", "已经记下", "记下了", "已记好", "已经记好", "记好了",
            "已记录", "已经记录", "已保存", "已经保存", "已存好",
            "已创建", "已经创建", "已建立", "已经建立", "已登记", "已经登记",
            "已添加", "已经添加", "已提交", "已经提交",
            "已提醒", "已经提醒", "已为您提醒", "已安排", "已经安排");

    private WriteClaims() { }

    /** 这句话是否在宣称某件写操作已经完成。 */
    public static boolean announces(String text) {
        if (text == null || text.isBlank()) return false;
        for (String word : CLAIMS) if (text.contains(word)) return true;
        return false;
    }
}
